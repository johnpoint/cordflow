const translations = { en, 'zh-CN': zhCN } as const;
export type MessageKey = keyof typeof en;

export function detectLocale(stored: string | null, languages: readonly string[]): Locale {
  if (stored === 'en' || stored === 'zh-CN') return stored;
  return languages.some((language) => language.toLowerCase().startsWith('zh')) ? 'zh-CN' : 'en';
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const template = translations[locale]?.[key] ?? translations.en[key];
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function setDocumentLocale(locale: Locale): void {
  document.documentElement.lang = locale;
}
